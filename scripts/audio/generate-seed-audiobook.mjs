/**
 * Generates the CC0 synthetic audiobook under src/features/player/fixtures/seed/.
 * Run: node scripts/audio/generate-seed-audiobook.mjs
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = join(root, 'src/features/player/fixtures/seed');
mkdirSync(outDir, { recursive: true });

const sampleRate = 8000;
const toneSec = 0.8;
const chapters = [
  { name: '01-opening.wav', freq: 440 },
  { name: '02-middle.wav', freq: 523.25 },
  { name: '03-closing.wav', freq: 659.25 },
];

function wavBuffer(durationSec, freqHz) {
  const numSamples = Math.floor(sampleRate * durationSec);
  const dataSize = numSamples * 2;
  const buf = Buffer.alloc(44 + dataSize);
  buf.write('RIFF', 0);
  buf.writeUInt32LE(36 + dataSize, 4);
  buf.write('WAVE', 8);
  buf.write('fmt ', 12);
  buf.writeUInt32LE(16, 16);
  buf.writeUInt16LE(1, 20);
  buf.writeUInt16LE(1, 22);
  buf.writeUInt32LE(sampleRate, 24);
  buf.writeUInt32LE(sampleRate * 2, 28);
  buf.writeUInt16LE(2, 32);
  buf.writeUInt16LE(16, 34);
  buf.write('data', 36);
  buf.writeUInt32LE(dataSize, 40);
  for (let i = 0; i < numSamples; i++) {
    const t = i / sampleRate;
    const sample = Math.sin(2 * Math.PI * freqHz * t) * 0.25;
    buf.writeInt16LE(Math.round(sample * 32767), 44 + i * 2);
  }
  return buf;
}

for (const ch of chapters) {
  writeFileSync(join(outDir, ch.name), wavBuffer(toneSec, ch.freq));
}

// 64×64 PNG (solid indigo) — minimal valid PNG, CC0.
const png = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAEAAAABACAYAAACqaXHeAAAAI0lEQVR4nO3BAQ0AAADCoPdPbQ8HFAAAAAAAAAAA8G8GKAAABWZJREFUAw==',
  'base64',
);
writeFileSync(join(outDir, 'cover.png'), png);

writeFileSync(
  join(outDir, 'PROVENANCE.md'),
  `# Review seed audiobook

Synthetic sine-wave chapters (no speech), generated by \`scripts/audio/generate-seed-audiobook.mjs\`.
Dedicated to the public domain (CC0 1.0). Cover is a minimal generated PNG, also CC0.
`,
);

console.log('Wrote seed fixtures to', outDir);
