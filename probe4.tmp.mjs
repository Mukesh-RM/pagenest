import { chromium } from '@playwright/test';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 412, height: 860 }, deviceScaleFactor: 2, permissions: ['clipboard-read','clipboard-write'] });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message, e.stack?.split('\n').slice(0,6).join('\n')));
page.on('console', (m) => { if (m.type()==='error') console.log('ERR', m.text().slice(0,400)); });
await page.goto('http://localhost:5199/dev/reader');
await page.getByRole('button', { name: /EPUB · stored as “book/ }).first().click();
await page.waitForSelector('.pn-reader__status');
await page.waitForTimeout(1200);
const s = (n) => page.screenshot({ path: `/workspace/scratch/s-${n}.png` });
// go to chapter 1 via contents
await page.getByRole('button', { name: /^Contents/ }).click();
await page.waitForTimeout(500);
await s('contents');
const items = page.locator('.pn-list__row');
console.log('toc rows', await items.count());
await items.nth(3).click();
await page.waitForTimeout(1200);
await s('chapter');
await page.getByRole('button', { name: 'Text and look' }).click();
await page.waitForTimeout(600);
await s('aa');
await page.keyboard.press('Escape');
await page.waitForTimeout(500);
await page.getByRole('button', { name: 'Search in book' }).click();
await page.getByRole('searchbox').fill('rabbit');
await page.waitForTimeout(2500);
await s('search');
await b.close();
